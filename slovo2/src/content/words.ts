function parse(): Word[] {
  const out: Word[] = [];
  for (const line of RAW) {
    const [text, stress, syll, danger, kind, emoji, sentence, hint, mnemonic] = line.split('|');
    out.push({
      id: `g2_${text}`,
      text,
      stress: Number(stress),
      syllables: syll.split('-'),
      danger: danger.split(',').map(Number),
      dangerKind: kind as DangerKind,
      emoji,
      sentence,
      hint,
      mnemonic: mnemonic || undefined,
      theme: THEME_OF[text] ?? 'school',
    });
  }
  return out;
}

export const WORDS: Word[] = parse();

export const WORD_BY_ID: Record<string, Word> = Object.fromEntries(WORDS.map((w) => [w.id, w]));

